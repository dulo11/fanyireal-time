const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const read = file => fs.readFileSync(path.join(__dirname, "..", file), "utf8");
const manifest = JSON.parse(read("manifest.json"));
const firefox = JSON.parse(read("compat/firefox/manifest.json"));
const select = read("content/selection-tools.js");
const floating = read("content/floating-panel.js");
const popup = read("popup/popup.js");
const html = read("popup/popup.html");
for (const m of [manifest, firefox]) assert.equal(m.version, "1.3.15");
assert.ok(manifest.content_scripts[0].js.includes("content/selection-tools.js"));
assert.match(select, /selectionToolsEnabled: true/);
assert.match(select, /selectionTargetLang: "page"/);
assert.match(select, /selectionTargetEl\.addEventListener\("change"/);
assert.match(select, /chrome\.storage\.sync\.set\(\{ selectionTargetLang/);
assert.match(select, /root\.getElementById\("retranslate"\)/);
assert.match(select, /root\.getElementById\("copyOriginal"\)/);
assert.match(select, /root\.getElementById\("copyBoth"\)/);
assert.match(select, /if \(!value\) return/); // avoid accidentally copying error or loading state
assert.match(select, /if \(lastTranslated\) void copyResult/);
assert.match(select, /options\.selectionToolsEnabled === false/);
assert.match(floating, /id="displayMode"/);
assert.match(floating, /id="inputTarget"/);
assert.match(floating, /id="selectionToolsEnabled"/);
assert.match(floating, /saveSync\(\{ displayMode: event\.target\.value \}\)/);
assert.match(floating, /saveSync\(\{ inputTargetLang: event\.target\.value \}\)/);
assert.match(html, /id="selectionTargetLang"/);
assert.match(html, /id="selectionToolsEnabled"/);
assert.match(popup, /saveSync\(\{ selectionTargetLang: event\.target\.value \}\)/);
assert.match(popup, /saveSync\(\{ selectionToolsEnabled: event\.target\.checked \}\)/);
const start = select.indexOf("  function resolvedTargetLanguage() {");
const end = select.indexOf("\n  async function translateSelection(", start);
assert.ok(start >= 0 && end > start);
const options = { selectionTargetLang: "page", targetLang: "vi" };
const context = { options };
vm.runInNewContext(select.slice(start, end), context);
assert.equal(context.resolvedTargetLanguage(), "vi", "Follow page language");
options.selectionTargetLang = "en";
assert.equal(context.resolvedTargetLanguage(), "en", "Independent selection target");
options.selectionTargetLang = "page";
options.targetLang = "zh-CN";
assert.equal(context.resolvedTargetLanguage(), "zh-CN", "Chinese selection target is allowed, no automatic skip");
console.log("v1.3.15 selection and mobile floating shortcuts tests passed");
